"""Build the GitHub Marketplace copy of the Parinama Verify action.

Plain words: GitHub's Marketplace (the store where people find ready-made workflow
steps) only lists an action whose `action.yml` sits at the top of its own repository.
Ours lives in `product/verify/` of this repository, next to pkv's code, so it can use
that code directly. The Marketplace copy can't: it has to fetch pkv. This script makes
the Marketplace copy from the original, so the two never drift apart. The only
differences are one extra step that downloads the released pkv from PyPI and refuses
to run it unless its fingerprint matches the published one, and the place pkv is
loaded from.

Engineering: a pure text transformation of product/verify/action.yml (standard
library only, no YAML parser needed). The wheel is pinned by URL and SHA-256; the
same hash is in the GitHub release's SHA256SUMS for tag pkv-v0.2.1. A self-check
(product/verify/tests/test_marketplace_action.py) requires the committed
product/action/action.yml to equal this script's output, and VERSION to equal the
package version, so a release can't forget to update the Marketplace copy.

Usage, from the repository root:
    python3 product/action/build.py           # rewrite product/action/action.yml
    python3 product/action/build.py --check   # fail if it is out of date
"""
from __future__ import annotations

import sys
from pathlib import Path

VERSION = "0.2.1"
WHEEL_URL = ("https://files.pythonhosted.org/packages/3a/7d/bd51de17b1a1c70ac371eeaa502d48360aadec6cbdc04ae496228f46d07b/"
             "parinama_verify-0.2.1-py3-none-any.whl")
WHEEL_SHA256 = "010ae72465c3c6c4d48d4b47c463c00acb58f7a70c8fc47c04c17c0e3024dbae"

HERE = Path(__file__).resolve().parent
SOURCE = HERE.parent / "verify" / "action.yml"
TARGET = HERE / "action.yml"

HEADER = f"""\
# Parinama Verify as a GitHub Action (the GitHub Marketplace copy, pkv {VERSION}).
#
# GENERATED by product/action/build.py from product/verify/action.yml in
# https://github.com/broly18814/parinamakramam . Don't edit this file by hand.
#
# Plain words: a ready-made step for a GitHub workflow. On every pull request
# or upload it works out which tests the change could affect, runs them,
# looks for signs the tests were weakened, and puts the receipt on the run's
# summary page. The job fails if the verdict is one you choose to block on.
#
# Security: the first step downloads pkv {VERSION} from PyPI once and refuses to
# run it unless its SHA-256 fingerprint equals the published one (the same as in
# the GitHub release's SHA256SUMS). After that, pkv uses no network and no AI.
# Every input reaches the shell through environment variables, never pasted
# into a command, so a crafted branch name or input can't inject commands.
"""

INSTALL_STEP = f"""\
    - id: install
      name: Download Parinama Verify {VERSION} from PyPI and check its fingerprint
      shell: bash
      env:
        PKV_PYTHON: ${{{{ inputs.python }}}}
        PKV_WHEEL_URL: {WHEEL_URL}
        PKV_WHEEL_SHA256: {WHEEL_SHA256}
        PKV_DIR: ${{{{ runner.temp }}}}/parinama-verify-{VERSION}
      run: |
        "$PKV_PYTHON" - <<'PY'
        import hashlib, io, os, urllib.request, zipfile
        data = urllib.request.urlopen(os.environ["PKV_WHEEL_URL"], timeout=120).read()
        got = hashlib.sha256(data).hexdigest()
        if got != os.environ["PKV_WHEEL_SHA256"]:
            raise SystemExit("::error title=Parinama Verify::the downloaded pkv has fingerprint "
                             + got + ", not the published one; refusing to run it")
        zipfile.ZipFile(io.BytesIO(data)).extractall(os.environ["PKV_DIR"])
        PY
        echo "path=$PKV_DIR" >> "$GITHUB_OUTPUT"

"""


def build(source: str) -> str:
    """The Marketplace action.yml, made from the original's text."""
    body = source[source.index("name: Parinama Verify\n"):]
    marker = "    - id: check\n"
    old_path = "        PYTHONPATH: ${{ github.action_path }}\n"
    new_path = "        PYTHONPATH: ${{ steps.install.outputs.path }}\n"
    if body.count(marker) != 1 or body.count(old_path) != 1:
        raise ValueError("product/verify/action.yml changed shape; update product/action/build.py")
    body = body.replace(marker, INSTALL_STEP + marker).replace(old_path, new_path)
    return HEADER + "\n" + body


def main(argv: list[str]) -> int:
    want = build(SOURCE.read_text())
    if "--check" in argv:
        if not TARGET.exists() or TARGET.read_text() != want:
            print("product/action/action.yml is out of date: run python3 product/action/build.py")
            return 1
        print("product/action/action.yml is up to date")
        return 0
    TARGET.write_text(want)
    print(f"wrote {TARGET.relative_to(HERE.parent.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
